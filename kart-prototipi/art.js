export function cardArtUrl(id) {
  if (!ART[id]) throw new Error(`Kart görseli bulunamadı: ${id}`);
  return new URL(ART[id].file, import.meta.url).href;
}

export function applyCardArt(element, id) {
  const art = ART[id];
  element.style.backgroundImage = `url("${cardArtUrl(id)}")`;
  element.style.backgroundSize = "200% 200%";
  element.style.backgroundPosition = art.position;
  element.style.backgroundRepeat = "no-repeat";
  element.setAttribute("role", "img");
  element.setAttribute("aria-label", art.alt);
}
